-- ลายเซ็นท้ายอีเมล (HTML) ต่อท้ายทุกอีเมลอัตโนมัติ — ว่าง = ไม่มีลายเซ็น
alter table settings add column if not exists signature_html text not null default '';

-- แนบไฟล์ไปกับอีเมลส่งซ้ำด้วยหรือไม่ (ค่าเริ่มต้น: แนบเฉพาะอีเมลรอบแรก)
alter table campaigns add column if not exists followup_attach boolean not null default false;
